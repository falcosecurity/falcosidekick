package database

import (
	"bytes"
	"encoding/json"
)

// sameConfig compares two configs by their JSON form, so values read back from a store
// (float64 numbers, map[string]any objects) equal the YAML values they were written from.
func sameConfig(a, b map[string]any) bool {
	left, err := json.Marshal(a)
	if err != nil {
		return false
	}
	right, err := json.Marshal(b)
	if err != nil {
		return false
	}
	return bytes.Equal(left, right)
}
