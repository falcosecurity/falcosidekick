export function iconForOutputType(type: string | undefined, fallback?: string): LucideIcon {
  const tryKey = (v: string | undefined) => {
    if (!v) return undefined
    return ICON_BY_TYPE[v.toLowerCase().replace(/[_\s-]/g, "")]
  }
  return tryKey(type) ?? tryKey(fallback) ?? Activity
}
