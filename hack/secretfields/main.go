// Command secretfields writes the secret fields of every output type, from the output schema, to
// the file the Helm chart reads to refuse credentials written inline in its values. Run it from the
// repository root; with -check it writes nothing and fails when the file is out of date.
package main

import (
	"flag"
	"fmt"
	"maps"
	"os"
	"slices"
	"strings"

	"github.com/falcosecurity/falcosidekick/internal/domain/output"
	"github.com/falcosecurity/falcosidekick/internal/outputs/all"
)

// Path is the generated file, relative to the repository root.
const Path = "chart/falcosidekick/files/secret-fields.yaml"

func main() {
	check := flag.Bool("check", false, "fail when the file differs instead of writing it")
	flag.Parse()
	if err := run(*check); err != nil {
		_, _ = fmt.Fprintln(os.Stderr, "secretfields:", err)
		os.Exit(1)
	}
}

func run(check bool) error {
	want := Generate(all.Types())
	current, err := os.ReadFile(Path)
	if err == nil && string(current) == want {
		return nil
	}
	if check {
		return fmt.Errorf("%s is out of date: run make chart.secret-fields", Path)
	}
	if err := os.WriteFile(Path, []byte(want), 0o644); err != nil { //nolint:gosec // chart file
		return err
	}
	_, _ = fmt.Println("wrote", Path)
	return nil
}

// Generate lists, per output type, the dotted paths of its string secrets, which take a
// <name>_file variant, and, per map field such as headers, the entry properties holding secrets.
func Generate(types []output.Type) string {
	lines := []string{"# Generated by hack/secretfields from the output schemas: run make chart.secret-fields."}
	sorted := slices.Clone(types)
	slices.SortFunc(sorted, func(a, b output.Type) int { return strings.Compare(a.Name, b.Name) })
	for _, typ := range sorted {
		var fields []string
		entries := map[string][]string{}
		for i := range typ.Schema.Fields {
			field := &typ.Schema.Fields[i]
			if field.HasFileVariant() {
				fields = append(fields, field.Name)
			}
			for j := range field.EntryFields {
				if field.EntryFields[j].Secret {
					entries[field.Name] = append(entries[field.Name], field.EntryFields[j].Name)
				}
			}
		}
		if len(fields) == 0 && len(entries) == 0 {
			continue
		}
		lines = append(lines, typ.Name+":")
		if len(fields) > 0 {
			slices.Sort(fields)
			lines = append(lines, "  fields:")
			for _, f := range fields {
				lines = append(lines, "    - "+f)
			}
		}
		if len(entries) > 0 {
			lines = append(lines, "  entries:")
			for _, name := range slices.Sorted(maps.Keys(entries)) {
				lines = append(lines, "    "+name+":")
				for _, secret := range slices.Sorted(slices.Values(entries[name])) {
					lines = append(lines, "      - "+secret)
				}
			}
		}
	}
	return strings.Join(lines, "\n") + "\n"
}
